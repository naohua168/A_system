# 验证板块云图SQL
cur.execute("""
  SELECT s.industry, COUNT(*), ROUND(AVG(d.change_percent), 2) as avg_change
  FROM stock_daily d JOIN stock s ON d.stock_code=s.stock_code
  WHERE d.trade_date=(SELECT MAX(trade_date) FROM stock_daily)
    AND s.industry IS NOT NULL AND s.industry != ''
  GROUP BY s.industry ORDER BY avg_change DESC
""")
