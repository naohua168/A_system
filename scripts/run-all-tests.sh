#!/bin/bash
# ============================================================
#  基金股票智能分析系统 - 一键测试运行脚本 (Linux/Mac)
#  运行所有模块的测试并输出报告
# ============================================================

set -e
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
EXIT_CODE=0

echo "============================================================"
echo "  StockAI 项目测试套件"
echo "  运行时间: $(date)"
echo "============================================================"
echo ""

# ============================================================
# 1. 后端测试 (Spring Boot + JUnit 5)
# ============================================================
echo "[1/4] 后端 Spring Boot 测试..."
cd "$ROOT/backend"
if mvn test -q 2>/dev/null; then
    echo "  [PASS] 后端测试通过"
else
    echo "  [FAIL] 后端测试失败"
    EXIT_CODE=1
fi
echo ""

# ============================================================
# 2. 前端测试 (Vitest)
# ============================================================
echo "[2/4] 前端 Vue3 测试..."
cd "$ROOT/frontend"
if npx vitest run 2>/dev/null; then
    echo "  [PASS] 前端测试通过"
else
    echo "  [FAIL] 前端测试失败"
    EXIT_CODE=1
fi
echo ""

# ============================================================
# 3. 分析算法测试 (pytest)
# ============================================================
echo "[3/4] 分析算法测试..."
cd "$ROOT/analysis-algorithms"
if python -m pytest tests/ -q 2>/dev/null; then
    echo "  [PASS] 分析算法测试通过"
else
    echo "  [FAIL] 分析算法测试失败"
    EXIT_CODE=1
fi
echo ""

# ============================================================
# 4. 数据采集测试 (pytest)
# ============================================================
echo "[4/4] 数据采集测试..."
cd "$ROOT/data-collector"
if python -m pytest tests/ -q 2>/dev/null; then
    echo "  [PASS] 数据采集测试通过"
else
    echo "  [FAIL] 数据采集测试失败"
    EXIT_CODE=1
fi
echo ""

# ============================================================
# 汇总
# ============================================================
echo "============================================================"
if [ $EXIT_CODE -eq 0 ]; then
    echo "  所有测试通过!"
else
    echo "  部分测试失败，请检查上方日志"
fi
echo "============================================================"

exit $EXIT_CODE
